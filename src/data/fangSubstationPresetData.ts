/**
 * Helper to scan all localStorage keys for any recoverable transformer data
 */
export function scanLocalStorageForBackups(): { key: string; sheetCount: number; transformerCount: number; data: any }[] {
  if (typeof window === 'undefined') return [];
  const results: { key: string; sheetCount: number; transformerCount: number; data: any }[] = [];

  try {
    for (let i = 0; i < localStorage.length; i++) {
      const key = localStorage.key(i);
      if (!key) continue;

      // Check keys related to pea, sheet, transformer, or backup
      if (
        key.includes('pea') || 
        key.includes('sheet') || 
        key.includes('transformer') || 
        key.includes('sld') ||
        key.includes('backup')
      ) {
        try {
          const raw = localStorage.getItem(key);
          if (!raw) continue;
          const parsed = JSON.parse(raw);

          // Check if it's an array of DiagramSheet
          if (Array.isArray(parsed) && parsed.length > 0) {
            let tfCount = 0;
            parsed.forEach((s: any) => {
              if (s && Array.isArray(s.transformers)) {
                tfCount += s.transformers.length;
              }
            });
            if (tfCount > 0) {
              results.push({
                key,
                sheetCount: parsed.length,
                transformerCount: tfCount,
                data: parsed
              });
            }
          } else if (Array.isArray(parsed) && parsed.length > 0 && parsed[0]?.peaNo) {
            // It's a direct array of Transformer
            results.push({
              key,
              sheetCount: 1,
              transformerCount: parsed.length,
              data: parsed
            });
          }
        } catch {
          // ignore non-json
        }
      }
    }
  } catch (err) {
    console.warn('Error scanning localStorage for backups:', err);
  }

  return results;
}
